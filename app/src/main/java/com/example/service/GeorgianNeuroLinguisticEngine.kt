    /**
     * Generates a list of sentence options for word selection dialogs/action sheets.
     */
    fun getContextualSentenceTemplates(word: String): List<String> {
        val trimmed = word.trim()
        val baseSentence = buildDynamicGeorgianSentence(trimmed)
        val entry = MIND_LEXICON_DATABASE.firstOrNull { it.word.equals(trimmed, ignoreCase = true) }

        val variants = mutableListOf(baseSentence)

        if (entry != null && entry.typicalNextWords.isNotEmpty()) {
            entry.typicalNextWords.take(3).forEach { next ->
                variants.add("მინდა $trimmed $next და შედეგი ვნახო.")
            }
        } else {
            variants.add("$trimmed დავიწყოთ და შევამოწმოთ.")
            variants.add("გთხოვთ $trimmed ყურადღებით დაამუშავოთ.")
        }

        return variants.distinct()
    }

    /**
     * Scored prediction based on multi-factor neural context.
     */
    fun predictCandidateWords(
        screenContext: String,
        currentCluster: String,
        stressLevel: Float,
        circadianHour: Int,
        limit: Int = 12
    ): List<MindLexiconEntry> {
        val scoredList = MIND_LEXICON_DATABASE.map { entry ->
            var score = 10.0f

            // 1. Screen Context Affinity
            when {
                screenContext.contains("IDE", ignoreCase = true) || screenContext.contains("Terminal", ignoreCase = true) -> {
                    if (entry.category == "DEV" || entry.category == "MORPHOLOGY_VERBS") score += 35.0f
                }
                screenContext.contains("Messaging", ignoreCase = true) || screenContext.contains("Chat", ignoreCase = true) -> {
                    if (entry.category == "COMMON" || entry.category == "EMOTIONS") score += 35.0f
                }
                screenContext.contains("Research", ignoreCase = true) || screenContext.contains("Docs", ignoreCase = true) -> {
                    if (entry.category == "NEURO_SCIENCE" || entry.category == "OBJECTS" || entry.category == "MORPHOLOGY_VERBS") score += 35.0f
                }
                else -> {
                    if (entry.category == "OBJECTS" || entry.category == "NATURE" || entry.category == "COMMON") score += 25.0f
                }
            }

            // 2. Subvocal Consonant Cluster Match (Fast Decimation)
            if (currentCluster.isNotBlank()) {
                val cleanCluster = currentCluster.replace("-", "").trim()
                if (entry.word.startsWith(cleanCluster, ignoreCase = true) || entry.rootStem.startsWith(cleanCluster)) {
                    score += 50.0f + (entry.clusterSpeedupGainPct * 0.3f)
                }
            }

            // 3. Circadian & Stress Calibration
            if (stressLevel > 0.6f && (entry.category == "EMOTIONS" || entry.word.contains("სიმშვიდე") || entry.word.contains("შესვენება"))) {
                score += 25.0f
            }

            if (circadianHour in 9..18 && (entry.category == "DEV" || entry.category == "MORPHOLOGY_VERBS" || entry.category == "OBJECTS")) {
                score += 15.0f
            }

            // Base frequency bonus
            score += (entry.emgFrequencyHz / 20.0f)

            Pair(entry, score)
        }

        return scoredList
            .sortedByDescending { it.second }
            .take(limit)
            .map { it.first }
    }

    /**
     * Markov / Contextual word prediction given the previous word and environment context.
     */
    fun predictBestCandidates(
        previousWord: String,
        screenContext: String,
        circadianHour: Int,
        stressLevel: Float,
        limit: Int = 4
    ): List<MindLexiconEntry> {
        val prevEntry = MIND_LEXICON_DATABASE.find { it.word.equals(previousWord.trim(), ignoreCase = true) }
        val typicalNext = prevEntry?.typicalNextWords ?: emptyList()

        if (typicalNext.isNotEmpty()) {
            val markovMatches = MIND_LEXICON_DATABASE.filter { entry ->
                typicalNext.any { next -> entry.word.contains(next, ignoreCase = true) || next.contains(entry.word, ignoreCase = true) }
            }
            if (markovMatches.isNotEmpty()) {
                val remainder = predictCandidateWords(screenContext, "", stressLevel, circadianHour, limit)
                return (markovMatches + remainder).distinctBy { it.word }.take(limit)
            }
        }

        return predictCandidateWords(screenContext, "", stressLevel, circadianHour, limit)
    }

    /**
     * Finds the nearest Georgian phonetic match for an incoming EMG frequency spike.
     */
    fun snapToNearestPhoneticWord(frequencyHz: Float, categoryFilter: String = "ALL"): MindLexiconEntry {
        val candidates = if (categoryFilter == "ALL") {
            MIND_LEXICON_DATABASE
        } else {
            MIND_LEXICON_DATABASE.filter { it.category == categoryFilter }
        }

        return candidates.minByOrNull { Math.abs(it.emgFrequencyHz - frequencyHz) }
            ?: MIND_LEXICON_DATABASE.first()
    }

    /**
     * Converts a string into phoneme tokens.
     */
    fun getPhonemesForString(input: String): List<String> {
        return input.map { char ->
            if (char.isWhitespace()) "␣" else char.toString()
        }
    }
